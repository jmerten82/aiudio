"""The capability manifest (Phase 2 · A1, ADR-0021) — the single grounding source of truth.

Generated by **introspecting the real node registry** (never hand-maintained): for each factory
kind, instantiate a sample node and read its type, ports, parameter descriptors (name / suggested
range / default / unit, from the C++ `paramDescriptors`), config, and RT-capability. Consumed by
both the UI (palette + typed editors) and the agent (grounded tools) — so neither can drift from,
or hallucinate beyond, what the pipeline actually offers.
"""
from __future__ import annotations

from functools import lru_cache

import aiudio

from .session import available_kinds

# Representative constructor args for factories that require them (others use binding defaults).
# These only produce a *sample instance* to introspect — the param metadata itself comes from C++.
_SAMPLE_ARGS: dict[str, dict] = {
    "gain": {"gain": 1.0},
    "biquad_lowpass": {"freq": 1000.0, "q": 0.707, "sample_rate": 48000.0},
    "biquad_highpass": {"freq": 1000.0, "q": 0.707, "sample_rate": 48000.0},
    "biquad_peaking": {"freq": 1000.0, "q": 1.0, "gain_db": 0.0, "sample_rate": 48000.0},
    "biquad_lowshelf": {"freq": 1000.0, "q": 1.0, "gain_db": 0.0, "sample_rate": 48000.0},
    "biquad_highshelf": {"freq": 1000.0, "q": 1.0, "gain_db": 0.0, "sample_rate": 48000.0},
    "biquad_coeffs": {"b0": 1.0, "b1": 0.0, "b2": 0.0, "a1": 0.0, "a2": 0.0},
    "latency": {"frames": 64},
    "parametric_eq": {"bands": [("peaking", 1000.0, 1.0, 0.0)], "sample_rate": 48000.0},
    "channel_matrix": {"in_channels": 2, "out_channels": 2},
}


def node_manifest(kind: str) -> dict:
    """Introspect one factory kind into a manifest entry."""
    graph = aiudio.Graph()
    node_id = getattr(graph, "add_" + kind)(**_SAMPLE_ARGS.get(kind, {}))
    _id, type_name, num_in, num_out = next(t for t in graph.nodes() if t[0] == node_id)
    config = dict(graph.node_config(node_id))
    return {
        "kind": kind,
        "type": type_name,
        "num_inputs": num_in,
        "num_outputs": num_out,
        "params": list(graph.param_descriptors(node_id)),
        "config": config,
        "realtime_capable": config.get("realtime_capable", 1.0) != 0.0,
        # sensible constructor args for "add this node" (the sample args used above) — so a UI/agent
        # can create any kind, including those whose factory requires args (gain, biquads, …).
        "defaults": dict(_SAMPLE_ARGS.get(kind, {})),
    }


@lru_cache(maxsize=1)
def capability_manifest() -> dict:
    """The full manifest: ``{"kinds": {kind: node_manifest(kind), ...}}`` — the grounding SoT."""
    return {"kinds": {kind: node_manifest(kind) for kind in available_kinds()}}


def param_issues(kind: str, index: int, value: float) -> list[str]:
    """Validate a `set_param` against the manifest — unknown kind/index, or value outside the
    declared range. Returns a (possibly empty) list of human-readable issues; the UI/agent surface
    these. (Ranges are UI suggestions — the session hard-rejects only an unknown index.)"""
    entry = capability_manifest()["kinds"].get(kind)
    if entry is None:
        return [f"unknown node kind: {kind!r}"]
    by_index = {int(d["index"]): d for d in entry["params"]}
    if not by_index:
        return []                                   # node has no described params — nothing to check
    if index not in by_index:
        return [f"{kind} has no parameter index {index}"]
    d = by_index[index]
    if not (d["min"] <= value <= d["max"]):
        return [f"{kind}.{d['name']} = {value} is outside [{d['min']}, {d['max']}] {d['unit']}".rstrip()]
    return []
